// =====================================================================
// UILayer.cs
// UI 레이어 분류 — Canvas sortingOrder와 라이프사이클 정책 결정의 기준
//
// 분류 기준:
//   World    : 월드 공간 UI (네임플레이트, 데미지 숫자)
//   HUD      : 상시 표시 (미니맵, 체력, 스태미나, 핫바, 퀘스트 트래커)
//              — 클릭 받지 않음 (정보 표시만)
//   Window   : 열고 닫는 패널, 여러 개 동시 가능 (인벤·퀘스트 팝업·스킬·공장 UI)
//              — 게임 일시정지 안 함, 입력은 차단
//   Modal    : 배타적, 뒤 클릭 차단 (확인 팝업, 설정, 분할 팝업)
//              — 게임 일시정지 함, 입력 차단
//   Toast    : 자동 사라짐 (퀘스트 완료 알림)
//   Overlay  : 항상 최상단 (로딩, 사망 오버레이, 페이드)
// =====================================================================

namespace TimeKov.UI
{
    public enum UILayer
    {
        World   = 0,
        HUD     = 1,
        Window  = 2,
        Modal   = 3,
        Toast   = 4,
        Overlay = 5
    }
}
